import sys
from datetime import date
from pathlib import Path
 
import duckdb
 
DB_PATH = "data/chinook.duckdb"
OUT_PATH = Path("docs/kpi_report.md")
 
 
def md_table(headers: list[str], rows: list[list]) -> str:
    """Build a Markdown table from headers and already formatted rows."""
    lines = ["| " + " | ".join(headers) + " |",
             "|" + "|".join("---" for _ in headers) + "|"]
    for row in rows:
        lines.append("| " + " | ".join(str(cell) for cell in row) + " |")
    return "\n".join(lines)
 
 
def money(value) -> str:
    return "–" if value is None else f"{float(value):,.2f}"
 
 
def pct(value) -> str:
    return "–" if value is None else f"{float(value):.2f}%"
 
 
def signed_pct(value) -> str:
    return "–" if value is None else f"{float(value):+.2f}%"
 
 
def coverage_section(con) -> str:
    invoices, customers, first, last, revenue = con.execute("""
        SELECT count(*), count(DISTINCT customer_id),
               min(CAST(invoice_ts AS DATE)), max(CAST(invoice_ts AS DATE)),
               sum(total)
        FROM stg_invoice
    """).fetchone()
    return "\n".join([
        "## Data coverage",
        "",
        f"- Invoices: {invoices} from {customers} customers",
        f"- Period: {first} to {last}",
        f"- Total revenue: {money(revenue)}",
    ])
 
 
def quality_section(con) -> str:
    rows = con.execute("""
        SELECT check_name, failed_rows, checked_rows, status
        FROM quality_report ORDER BY check_name
    """).fetchall()
    passed = sum(1 for r in rows if r[3] == "pass")
    table = md_table(["Check", "Failed rows", "Checked rows", "Status"],
                     [[r[0], r[1], r[2], r[3]] for r in rows])
    return "\n".join([
        "## Data quality",
        "",
        f"{passed} of {len(rows)} checks passed. Checks are defined in `sql/02_quality.sql`.",
        "",
        table,
    ])
 
 
def year_section(con) -> str:
    rows = con.execute("""
        SELECT invoice_year, invoices, customers, revenue, avg_invoice_value,
               last_invoice_date, revenue_yoy_pct
        FROM kpi_revenue_by_year ORDER BY invoice_year
    """).fetchall()
    table = md_table(
        ["Year", "Invoices", "Customers", "Revenue", "Avg invoice", "Last invoice", "YoY change"],
        [[r[0], r[1], r[2], money(r[3]), money(r[4]), str(r[5])[:10], signed_pct(r[6])] for r in rows])
    return "\n".join([
        "## KPI 1: Revenue per year",
        "",
        table,
        "",
        "![Revenue per year](img/revenue_by_year.png)",
    ])
 
 
def genre_section(con) -> str:
    rows = con.execute("""
        SELECT revenue_rank, genre_name, revenue, units_sold, revenue_share_pct, cumulative_share_pct
        FROM kpi_revenue_by_genre ORDER BY revenue_rank, genre_name
    """).fetchall()
    table = md_table(
        ["Rank", "Genre", "Revenue", "Units sold", "Share", "Cumulative share"],
        [[r[0], r[1], money(r[2]), int(r[3]), pct(r[4]), pct(r[5])] for r in rows])
    return "\n".join([
        "## KPI 2: Revenue by genre",
        "",
        table,
        "",
        "![Revenue by genre](img/revenue_by_genre.png)",
    ])
 
 
def artist_section(con) -> str:
    total = con.execute("SELECT count(*) FROM kpi_revenue_by_artist").fetchone()[0]
    rows = con.execute("""
        SELECT revenue_rank, artist_name, revenue, units_sold, albums_sold, revenue_share_pct
        FROM kpi_revenue_by_artist ORDER BY revenue_rank, artist_name LIMIT 10
    """).fetchall()
    table = md_table(
        ["Rank", "Artist", "Revenue", "Units sold", "Albums sold", "Share"],
        [[r[0], r[1], money(r[2]), int(r[3]), r[4], pct(r[5])] for r in rows])
    return "\n".join([
        "## KPI 3: Revenue by artist",
        "",
        f"Top 10 of {total} artists with sales. The full list is in the view `kpi_revenue_by_artist`.",
        "",
        table,
        "",
        "![Top 10 artists](img/top10_artists.png)",
    ])
 
 
def main() -> int:
    if not Path(DB_PATH).exists():
        print(f"{DB_PATH} not found. Run: make load && make sql")
        return 1
    con = duckdb.connect(DB_PATH, read_only=True)
    try:
        sections = [
            "# KPI report",
            "",
            f"Generated by `src/report.py` on {date.today()}. Do not edit by hand.",
            "",
            coverage_section(con), "",
            quality_section(con), "",
            year_section(con), "",
            genre_section(con), "",
            artist_section(con), "",
        ]
    except duckdb.CatalogException as err:
        print(f"A view is missing. Run: make sql\n{err}")
        return 1
    finally:
        con.close()
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text("\n".join(sections))
    print(f"saved {OUT_PATH}")
    return 0
 
 
if __name__ == "__main__":
    sys.exit(main())